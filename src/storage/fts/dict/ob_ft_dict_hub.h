class ObFTDictInfo
{
public:
  ObFTDictInfo()
      : name_(""),
        type_(ObFTDictType::DICT_TYPE_INVALID),
        charset_(CHARSET_INVALID),
        version_(0),
        range_count_(0)
  {
  }

public:
  char name_[2048]; // for now
  ObFTDictType type_;
  ObCharsetType charset_;
  int64_t version_; // in memory
  int32_t range_count_;
};

struct ObFTDictInfoKey
{
public:
  ObFTDictInfoKey()
      : type_(static_cast<uint64_t>(ObFTDictType::DICT_TYPE_INVALID))
  {
  } // default constructor
  ObFTDictInfoKey(const uint64_t type)
      : type_(type)
  {
  }
  int hash(uint64_t &hash_value) const
  {
    int ret = OB_SUCCESS;
    hash_value = hash();
    return ret;
  }

  uint64_t hash() const
  {
    uint64_t hash = 0;
    hash = common::murmurhash(&type_, sizeof(int64_t), hash);
    return hash;
  }

  bool operator==(const ObFTDictInfoKey &other) const
  {
    return type_ == other.type_;
  }

  int compare(const ObFTDictInfoKey &other) const
  {
    int ret = 0;
    if (0 == ret) {
      ret = type_ - other.type_;
    }
    return ret;
  }

private:
  uint64_t type_;
  // name
};

class ObFTCacheRangeContainer;
class ObFTDictHub
{
public:
  ObFTDictHub() : is_inited_(false), dict_map_(), rw_dict_lock_(), cached_dict_mutex_() {}
  ~ObFTDictHub() {}

  int init();

  int destroy();

  int build_cache(const ObFTDictDesc &desc, ObFTCacheRangeContainer &container);

  int load_cache(const ObFTDictDesc &desc, ObFTCacheRangeContainer &container);

  // Returns the process-wide immutable dictionary for a built-in parser.  The
  // dictionary (including its pinned cache ranges) is built once and shared by
  // every tokenizer instance, so creating a parser no longer walks the KV cache
  // and rebuilds the range wrappers for every document.
  int get_cached_dict(const ObFTDictDesc &desc, ObIFTDict *&dict);

private:
  struct CachedDict
  {
    CachedDict()
      : alloc_(lib::ObMemAttr("FTDictShared")),
        container_(nullptr),
        dict_(nullptr),
        inited_(false)
    {}
    common::ObArenaAllocator alloc_;
    ObFTCacheRangeContainer *container_;
    ObIFTDict *dict_;
    bool inited_;
  };

  int get_dict_info(const ObFTDictInfoKey &key, ObFTDictInfo &info);

  int put_dict_info(const ObFTDictInfoKey &key, const ObFTDictInfo &info);

  int build_cached_dict(const ObFTDictDesc &desc, CachedDict &cached);

  static int64_t dict_type_to_slot(const ObFTDictType type);

private:
  static constexpr int64_t MAX_CACHED_DICT_NUM = 3;
  bool is_inited_;
  // holds info of dict
  hash::ObHashMap<ObFTDictInfoKey, ObFTDictInfo> dict_map_;
  ObBucketLock rw_dict_lock_;
  CachedDict cached_dicts_[MAX_CACHED_DICT_NUM];
  lib::ObMutex cached_dict_mutex_;
};

